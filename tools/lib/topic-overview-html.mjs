export function topicOverviewOutputs(topics, nodes, indexHtml) {
  const current = topics.filter(topic => topic.presentation === 'topic-overview');
  const paths = new Set();
  for (const topic of current) {
    validateTopicSource(topic, nodes);
    if (paths.has(topicPath(topic))) throw Error(`专题路径重复：${topicPath(topic)}`);
    paths.add(topicPath(topic));
  }
  const begin = indexHtml.indexOf(INDEX_BEGIN), end = indexHtml.indexOf(INDEX_END);
  if (begin < 0 || end < begin || indexHtml.indexOf(INDEX_BEGIN, begin + 1) >= 0 || indexHtml.indexOf(INDEX_END, end + 1) >= 0) throw Error('专题首页缺少唯一的生成区间');
  const outputs = new Map([['topics/index.html', indexHtml.slice(0, begin + INDEX_BEGIN.length) + '\n' + renderTopicIndex(current) + '\n    ' + indexHtml.slice(end)]]);
  for (const topic of current) outputs.set(`${topicPath(topic).slice(1)}index.html`, renderTopicOverview(topic, nodes));
  return outputs;
}
