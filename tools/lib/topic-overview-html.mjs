import {siteChrome, SITE_HEADER_CSS, BEGIN, END} from './site-header.mjs';
import {topicPath, validateTopicSource} from './public-knowledge-teaching.mjs';
import {textHtml} from './public-knowledge-html.mjs';

export const INDEX_BEGIN = '<!-- topic-overviews:begin -->';
export const INDEX_END = '<!-- topic-overviews:end -->';
export const PAGE_MARKER = '<!-- generated by tools/build-topic-overviews.mjs -->';
const h = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[c]));
const typeLink = group => `/knowledge/${group.type}/`;
const problemCount = topic => Object.keys(topic.problems).length;
const titleId = topic => `topic-${topic.id}`;

function topicCard(topic) {
  const count = problemCount(topic), href = topicPath(topic);
  return `<article class="topic-card" aria-labelledby="${titleId(topic)}">
  <div class="topic-top"><span class="topic-no">${h(topic.chapter.section)}</span>${count ? '' : '<span class="topic-building">题目建设中</span>'}</div>
  <h3 id="${titleId(topic)}"><a href="${href}">${h(topic.label)}</a></h3>
  <p class="topic-desc">${h(topic.introduction)}</p>
  <p class="topic-label">${topic.groups.length} 个题型</p>
  <ul class="topic-methods">${topic.groups.map(group => `<li><a href="${href}#group-${group.id}">${h(group.label)}</a></li>`).join('')}</ul>
  <div class="topic-foot"><span class="topic-count">${count ? `<b>${count}</b> 题` : '先了解知识与题型'}</span><a class="topic-go" href="${href}" aria-label="进入${h(topic.label)}专题">进入专题 →</a></div>
</article>`;
}

export function renderTopicIndex(topics) {
  const chapters = new Map();
  for (const topic of topics) {
    const key = JSON.stringify([topic.chapter.book, topic.chapter.number, topic.chapter.label]);
    if (!chapters.has(key)) chapters.set(key, []);
    chapters.get(key).push(topic);
  }
  return [...chapters.values()].map(group => {
    const {chapter} = group[0], id = `chapter-topic-${group[0].id}`;
    return `<section class="chapter topic-overview-chapter" aria-labelledby="${id}">
  <div class="chapter-heading"><p class="chapter-book">${h(chapter.book)} · ${h(chapter.number)}</p><h2 id="${id}">${h(chapter.label)}</h2></div>
  <div class="topic-grid">${group.map(topicCard).join('\n')}</div>
</section>`;
  }).join('\n');
}

function choiceStemParts(text) {
  const lines = String(text).split(/\r?\n/).map(line => line.trim()).filter(Boolean);
  const options = [];
  const prompt = [];
  for (const line of lines) {
    if (/^[A-D][.、．]/.test(line)) options.push(line);
    else if (options.length) options[options.length - 1] += ` ${line}`;
    else prompt.push(line);
  }
  return options.length >= 2 ? {prompt: prompt.join(' '), options} : null;
}

function problemStem(problem, position) {
  const text = problem.statement || problem.label;
  const choice = choiceStemParts(text);
  const body = choice
    ? `<span class="problem-prompt">${textHtml(choice.prompt)}</span><span class="problem-options">${
      choice.options.map(option => `<span class="problem-option">${textHtml(option)}</span>`).join('')
    }</span>`
    : textHtml(text);
  return `<span class="problem-number">${String(position).padStart(2, '0')}</span><span class="problem-stem"><span class="visually-hidden">第 ${position} 题：</span>${body}</span><span class="problem-go" aria-hidden="true">→</span>`;
}

function groupProblems(group, topic, byId) {
  if (!group.problems.length) return '<p class="topic-group-empty">题目建设中</p>';
  let position = 0;
  const list = ids => `<ol class="problem-list"${position ? ` start="${position + 1}"` : ''}>${ids.map(id => {
    const problem = topic.problems[id];
    return `<li><a class="problem-card" href="${h(problem.path)}" data-problem-id="${h(id)}">${problemStem(problem, ++position)}</a></li>`;
  }).join('')}</ol>`;
  if (group.groupBy !== 'method') return list(group.problems);
  const methods = new Map();
  for (const id of group.problems) {
    // The first course route is the default recommendation. Alternate routes
    // remain on the question page instead of duplicating its overview card.
    const method = Object.values(topic.problems[id].routes || {})[0]?.methods?.[0];
    if (byId.get(method)?.kind !== 'method') throw Error(`题目缺少可用于分组的默认方法：${id}`);
    if (!methods.has(method)) methods.set(method, []);
    methods.get(method).push(id);
  }
  const order = byId.get(group.type)?.methods || [];
  const rank = ref => order.includes(ref) ? order.indexOf(ref) : order.length;
  return [...methods].sort(([a], [b]) => rank(a) - rank(b)).map(([ref, ids]) => {
    const title = `title-${group.id}-${ref}`;
    return `<section class="topic-method-group" aria-labelledby="${title}"><h4 class="topic-method-title" id="${title}">${h(byId.get(ref).label)}</h4>${list(ids)}</section>`;
  }).join('\n');
}

